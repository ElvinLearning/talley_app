test('failed save preserves edits and navigation warns',async({page})=>{
  await login(page,'admin.demo')
  await page.getByRole('button',{name:'New job',exact:true}).click()
  await page.getByLabel('Customer name',{exact:true}).fill('Demo recovery customer')
  await page.getByLabel('Contact person',{exact:true}).fill('Demo contact')
  await page.getByLabel('Job name',{exact:true}).fill('Demo save recovery '+Date.now())
  await page.getByLabel('Site address',{exact:true}).fill('200 Example Street')
  await page.getByLabel('Scope of work',{exact:true}).fill('Synthetic failure-recovery test')
  await page.getByRole('button',{name:'Create job',exact:true}).click()
  await page.getByRole('button',{name:'Build estimate',exact:true}).first().click()
  await page.getByLabel('Description',{exact:true}).fill('Keep this edit after a failed save')
  await page.getByLabel('Unit cost',{exact:true}).fill('100')
  await page.route('**/api/estimates/*',async route=>{
    if(route.request().method()==='PUT')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Simulated service interruption'})})
    else await route.continue()
  })
  await page.getByRole('button',{name:'Save estimate',exact:true}).first().click()
  await expect(page.getByRole('alert')).toContainText('Simulated service interruption')
  await expect(page.getByLabel('Description',{exact:true})).toHaveValue('Keep this edit after a failed save')
  page.once('dialog',dialog=>dialog.dismiss())
  await page.getByRole('link',{name:/Demo save recovery/}).click()
  await expect(page.getByLabel('Description',{exact:true})).toBeVisible()
  await page.unroute('**/api/estimates/*')
  await page.getByRole('button',{name:'Save estimate',exact:true}).first().click()
  await expect(page.getByTestId('save-state').first()).toContainText('Saved')
})
